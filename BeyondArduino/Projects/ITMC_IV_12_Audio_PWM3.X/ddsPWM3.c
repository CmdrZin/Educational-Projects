// Larger val = higher frequency. 64:256:256*64. chan 0:2
void setInc(uint8_t chan, uint16_t val)
{
    if(chan < 3) {
        incChan[chan] = val;
    }
}

/* TCA interrupt service routine. */
// All of this needs to complete within 12us.
ISR(TCA0_OVF_vect)
{
    int i;
    static uint8_t index;
    static uint8_t newPWM[3];
    
    // Update from last calculations.
    TCA0.SINGLE.CMP0 = (uint16_t)newPWM[0];
    TCA0.SINGLE.CMP1 = (uint16_t)newPWM[1];
    TCA0.SINGLE.CMP2 = (uint16_t)newPWM[2];
    
    // Update PWM channels
    for(i=0; i<3; i++) {
        accumChan[i] += incChan[i]; // an incChan of 256 creates the base frequency.
        index = accumChan[i]>>8;
        newPWM[i] = pgm_read_byte(&ma_sinTable88[index]) + 137;     // shift to center
    }
    
//    newPWMX = pgm_read_byte(&ma_rampUpTable112[indexX]) + 128;     // shift to center
//    newPWMX = pgm_read_byte(&ma_rampDnTable112[indexX]) + 128;     // shift to center
//    newPWMX = pgm_read_byte(&ma_squareTable112[indexX]) + 128;     // shift to center
//    newPWM = pgm_read_byte(&ma_triangleTable112[index]) + 143;     // shift to center

    TCA0.SINGLE.INTFLAGS = TCA_SINGLE_OVF_bm;   // clear the interrupt flag
}


/* *** TCA Configuration as Single-Slope PWM with interrupt at OVF *** */
void init_dds(void)
{
	TCA0.SINGLE.PER = 0x00FF;       // 8-bit OVF count
    TCA0.SINGLE.CMP0 = 0x0080;      // square wave default
    TCA0.SINGLE.CMP1 = 0x8000;      // square wave default
    TCA0.SINGLE.CMP2 = 0x8000;      // square wave default
   	/* enable overflow interrupt */
	TCA0.SINGLE.INTCTRL = TCA_SINGLE_OVF_bm;
	/* set Single Slope PWM mode */
	TCA0.SINGLE.CTRLB = 0x70 | TCA_SINGLE_WGMODE_SINGLESLOPE_gc;
//	TCA0.SINGLE.CTRLB = 0x10 | TCA_SINGLE_WGMODE_SINGLESLOPE_gc;
	TCA0.SINGLE.CTRLA = TCA_SINGLE_CLKSEL_DIV1_gc  /* set CLK_PER/1 */
					| TCA_SINGLE_ENABLE_bm; 	/* start timer */
    
    // Clear accumulators
    accumChan[0] = 0;
    accumChan[1] = 0;
    accumChan[2] = 0;
    
    // Configure I/O pins as OUTPUT
    PORTB.DIR |= 0x07;              // all three. W0, W1, W2
//    PORTB.DIR |= 0x01;            // only WO
    
}

